# Verifies SC-1 for the built debug APK:
#   - The declared runtime/install permissions are exactly the five the spec allows:
#       SET_ALARM, POST_NOTIFICATIONS, FOREGROUND_SERVICE,
#       FOREGROUND_SERVICE_SPECIAL_USE, RECEIVE_BOOT_COMPLETED.
#   - REQUEST_IGNORE_BATTERY_OPTIMIZATIONS is absent.
#   - minSdk (from the merged manifest / badging) is 33.
#
# AGP auto-injects a private, app-namespaced permission
# "com.quickalarm.DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION" (declared + used) when an
# AndroidX receiver is registered with the RECEIVER_NOT_EXPORTED flag. It is internal
# plumbing, grants nothing to other apps, and is not something this app declares, so it
# is excluded from the "exactly five" comparison.
#
# Exits non-zero on any mismatch. Run after `.\gradlew.bat assembleDebug`.

[CmdletBinding()]
param(
    [string]$Apk = (Join-Path $PSScriptRoot '..\app\build\outputs\apk\debug\app-debug.apk')
)

$ErrorActionPreference = 'Stop'

$expected = @(
    'com.android.alarm.permission.SET_ALARM',
    'android.permission.POST_NOTIFICATIONS',
    'android.permission.FOREGROUND_SERVICE',
    'android.permission.FOREGROUND_SERVICE_SPECIAL_USE',
    'android.permission.RECEIVE_BOOT_COMPLETED'
) | Sort-Object

$forbidden = 'android.permission.REQUEST_IGNORE_BATTERY_OPTIMIZATIONS'
$autoGenerated = 'com.quickalarm.DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION'

if (-not (Test-Path $Apk)) {
    Write-Error "APK not found: $Apk. Run .\gradlew.bat assembleDebug first."
    exit 1
}

# Locate aapt2 in the SDK build-tools.
$aapt = (Get-ChildItem "$env:LOCALAPPDATA\Android\Sdk\build-tools\*\aapt2.exe" -ErrorAction SilentlyContinue |
    Sort-Object FullName -Descending | Select-Object -First 1).FullName
if (-not $aapt) { Write-Error "aapt2 not found under Android SDK build-tools."; exit 1 }

$apkAbs = (Resolve-Path $Apk).Path

# --- Permission set ---
$permDump = & $aapt dump permissions $apkAbs
$declared = $permDump | Select-String "uses-permission: name='([^']+)'" -AllMatches |
    ForEach-Object { $_.Matches.Groups[1].Value } | Sort-Object -Unique

if ($null -eq $declared) { $declared = @() }

# Forbidden must not appear at all.
if ($declared -contains $forbidden) {
    Write-Error "Forbidden permission present: $forbidden"
    exit 1
}

# Compare the "real" set (exclude the auto-generated internal permission).
$real = $declared | Where-Object { $_ -ne $autoGenerated } | Sort-Object
if (@(Compare-Object $expected $real -SyncWindow 0).Count -ne 0) {
    Write-Error "Permission set mismatch.`nExpected: $($expected -join ', ')`nActual:   $($real -join ', ')"
    exit 1
}

# --- minSdk from badging ---
$badging = & $aapt dump badging $apkAbs
$sdkLine = $badging | Select-String "sdkVersion:'(\d+)'"
if (-not $sdkLine) { Write-Error "Could not read sdkVersion from badging."; exit 1 }
$minSdk = [int]$sdkLine.Matches.Groups[1].Value
if ($minSdk -ne 33) {
    Write-Error "minSdk is $minSdk, expected 33."
    exit 1
}

Write-Host "SC-1 OK: permissions are exactly the five required, battery permission absent, minSdk=33."
exit 0
